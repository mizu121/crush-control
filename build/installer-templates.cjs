'use strict';
// Narrow project-owned overrides of MIT-licensed electron-builder templates.
// The dependency installation is never edited. Hash drift requires review.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const ROOT = path.resolve(__dirname, '..');
const OUTPUT = path.join(__dirname, 'installer-templates');
const UPSTREAM = path.join(ROOT, 'node_modules/app-builder-lib/templates/nsis');
const INPUTS = Object.freeze({
  'installer.nsi': '8811964416d122612c3e7601728af5d3f998d677918df829a4e8b4c739c8b9f8',
  'installSection.nsh': '74c4dbb4163cdd90ca4850b75d304e916235c882d6af7b5cdad63bffbc977072',
  'uninstaller.nsh': '9ee2dac4593478083e8aa6f8487287ce9401006ccd50ecc538871d133ea4a42c',
  'include/installer.nsh': '0e319437dd01dcbf911f3f48f664fde0cefbaef704f1cdb1739f63d563f5d4a0',
  'multiUser.nsh': '9aca256695c289ec8a875143101fae8c6236bc8c6a7cf369bbe8b4986e09c9cb',
});
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
function readInputs() {
  if (require('../node_modules/app-builder-lib/package.json').version !== '26.18.0') throw new Error('Review changed electron-builder version');
  return Object.fromEntries(Object.entries(INPUTS).map(([file, digest]) => {
    const bytes = fs.readFileSync(path.join(UPSTREAM, file));
    if (hash(bytes) !== digest) throw new Error(`Review changed NSIS template ${file}`);
    return [file, bytes.toString('utf8').replaceAll('\r\n', '\n')];
  }));
}
function replaceExactly(text, from, to, count = 1) {
  if (text.split(from).length - 1 !== count) throw new Error('Unexpected NSIS template replacement count');
  return text.split(from).join(to);
}
function generate() {
  const input = readInputs();
  const banner = '; Derived from electron-builder 26.18.0 under MIT; see LICENSE.electron-builder.txt.\n'
    + '; Project modifications remove external banner/shortcut plugins. Generated by installer-templates.cjs.\n';
  const prefix = '${PROJECT_DIR}\\build\\installer-templates\\';
  // Keep the default entry script: specifying nsis.script would bypass
  // electron-builder's standard two-pass generation of the uninstaller.
  if (!input['installer.nsi'].includes('!include "installSection.nsh"') || !input['installer.nsi'].includes('!include "uninstaller.nsh"')) throw new Error('Review changed default NSIS entry includes');
  let install = replaceExactly(input['installSection.nsh'], '!include installer.nsh', `!include "${prefix}installer-app-files.nsh"`);
  const start = install.indexOf('!ifdef ONE_CLICK\n');
  const end = install.indexOf('  !insertmacro CHECK_APP_RUNNING', start);
  if (start < 0 || end < 0 || !install.slice(start, end).includes('SpiderBanner::Show')) throw new Error('Missing reviewed one-click banner block');
  install = install.slice(0, start) + [
    '!ifdef ONE_CLICK',
    '  ; The built-in MUI instfiles page supplies installation progress.',
    '  ; Keep the shutdown-block reason, without an external decorative banner.',
    '  ${IfNot} ${Silent}',
    '    StrCpy $1 $hwndparent',
    "    System::Call 'user32::ShutdownBlockReasonCreate(${SYSTYPE_PTR}r1, w \"$(installing)\")'",
    '  ${endif}', '',
  ].join('\n') + install.slice(end);
  let files = input['include/installer.nsh'];
  const setLines = files.match(/^\s*WinShell::SetLnkAUMI[^\n]*$/gm) ?? [];
  const unlinkLines = files.match(/^\s*WinShell::UninstShortcut[^\n]*$/gm) ?? [];
  if (setLines.length !== 5 || unlinkLines.length !== 2) throw new Error('Review changed shortcut template calls');
  files = files.replace(/^(\s*)WinShell::SetLnkAUMI[^\n]*$/gm, '$1; The packaged app sets AUMI after verifying this shortcut target on first launch.')
    .replace(/^(\s*)WinShell::UninstShortcut[^\n]*$/gm, '$1; User-managed pins remain managed by Windows; the exact shortcut rename above is retained.');
  let uninstall = input['uninstaller.nsh'];
  const cleanupLines = uninstall.match(/^\s*WinShell::(?:UninstAppUserModelId|UninstShortcut)[^\n]*$/gm) ?? [];
  if (cleanupLines.length !== 3) throw new Error('Review changed uninstaller shortcut cleanup');
  uninstall = uninstall.replace(/^(\s*)WinShell::(?:UninstAppUserModelId|UninstShortcut)[^\n]*$/gm,
    '$1; No automatic pin/Jump List cleanup; exact installer-owned shortcut deletion below remains.');
  const result = {
    'installSection.nsh': banner + install,
    'installer-app-files.nsh': banner + files,
    'uninstaller.nsh': banner + uninstall,
    // The old pinned NSIS compiler cannot prepend include paths. Its built-in
    // MultiUser.nsh has an unrelated API. An unchanged cwd copy wins lookup.
    'multiUser.nsh': input['multiUser.nsh'],
    'LICENSE.electron-builder.txt': fs.readFileSync(path.join(ROOT, 'node_modules/electron-builder/LICENSE'), 'utf8').replaceAll('\r\n', '\n'),
  };
  if (/SpiderBanner::|WinShell::/.test(Object.values(result).join('\n'))) throw new Error('Removed plugin remains in template');
  result['UPSTREAM.json'] = JSON.stringify({
    package: 'app-builder-lib', version: '26.18.0', license: 'MIT',
    source: 'https://github.com/electron-userland/electron-builder/tree/master/packages/app-builder-lib/templates/nsis',
    exactLocalInputsSha256: INPUTS,
    outputsSha256: Object.fromEntries(Object.entries(result).map(([file, text]) => [file, hash(Buffer.from(text))])),
    modifications: ['default entry script and two-pass build retained; project include uses documented !cd/include lookup for three overrides and an unchanged multiUser template to resolve compiler-name collision', 'standard MUI progress replaces decorative SpiderBanner', 'first packaged app launch applies verified-shortcut AUMI instead of WinShell', 'automatic Windows pin/Jump List cleanup removed; existing exact shortcut file operations preserved'],
  }, null, 2) + '\n';
  return result;
}
function assertTemplatesCurrent() {
  for (const [file, expected] of Object.entries(generate())) {
    if (fs.readFileSync(path.join(OUTPUT, file), 'utf8') !== expected) throw new Error(`Regenerate/review NSIS override ${file}`);
  }
  return true;
}
function write() {
  fs.mkdirSync(OUTPUT, { recursive: true });
  for (const [file, text] of Object.entries(generate())) fs.writeFileSync(path.join(OUTPUT, file), text);
}
module.exports = { INPUTS, OUTPUT, readInputs, generate, replaceExactly, assertTemplatesCurrent, write };
if (require.main === module) {
  if (process.argv.includes('--write')) write(); else assertTemplatesCurrent();
  console.log('Verified pinned installer template overrides.');
}
